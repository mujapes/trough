#!/usr/bin/env python3
"""Generate the specs file that makes stock Debian gcc a Trough toolchain.

Reads `gcc -dumpspecs` on stdin, writes specs on stdout. GCC reads <libdir>/specs relative to
its own binary, so dropping this at d/usr/lib/gcc/aarch64-linux-gnu/14/specs is enough:
  - programs it links load through texec: -dynamic-linker /data/data/t.t/x
  - headers come from the Debian root: -isysroot in cpp_unique_options (what cc1 gets;
    cpp_options is NOT used for an integrated compile -- 10-27, headers silently came from
    the VM's own /usr/include)
  - the linker and startfiles (crt1.o) search the Debian root too.
"""
import re
import sys

R = "/data/data/t.t"
D = R + "/d"
s = sys.stdin.read()
old = "/lib/ld-linux-aarch64%{mbig-endian:_be}%{mabi=ilp32:_ilp32}.so.1"
assert s.count(old) == 1, "unexpected link spec"
s = s.replace(old, R + "/x")
for name, prefix in (("link", f"--sysroot={D} "), ("cpp_unique_options", f"-isysroot {D} ")):
    head = f"*{name}:\n"
    assert s.count(head) == 1, name
    s = s.replace(head, head + prefix, 1)
s, n = re.subn(r"\*startfile_prefix_spec:\n[^\n]*\n", f"*startfile_prefix_spec:\n{D}/usr/lib/aarch64-linux-gnu/\n", s, count=1)
assert n == 1
sys.stdout.write(f"# Trough: generated by tools/gcc_specs.py from stock gcc -dumpspecs.\n{s}")
