#!/bin/sh
# Regenerates native/present/shaders.h (SPIR-V as C arrays) from the GLSL sources with glslang.
# The header is committed so the phone builds without glslang; CI checks it is current.
set -eu
D=$(CDPATH= cd -- "$(dirname -- "$0")/../native/present" && pwd)
W=$(mktemp -d); trap 'rm -rf "$W"' EXIT
glslangValidator -V --target-env vulkan1.1 --vn rect_vert -o "$W/v.h" "$D/rect.vert" >/dev/null
glslangValidator -V --target-env vulkan1.1 --vn rect_frag -o "$W/f.h" "$D/rect.frag" >/dev/null
glslangValidator -V --target-env vulkan1.1 --vn glyph_vert -o "$W/gv.h" "$D/glyph.vert" >/dev/null
glslangValidator -V --target-env vulkan1.1 --vn glyph_frag -o "$W/gf.h" "$D/glyph.frag" >/dev/null
{ echo "/* Generated by tools/shaders.sh from rect.* and glyph.*; do not edit. */"
  echo "#include <stdint.h>"; cat "$W/v.h" "$W/f.h" "$W/gv.h" "$W/gf.h"; } > "$D/shaders.h"
